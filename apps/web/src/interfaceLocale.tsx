const LocaleContext = createContext<InterfaceLocale>("zh");

export function InterfaceLocaleProvider({ locale, children }: { locale: InterfaceLocale; children: ReactNode }) {
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export function useInterfaceLocale() {
  const locale = useContext(LocaleContext);
  const t = useCallback(
    (source: string) => locale === "en" ? ENGLISH[source] ?? source : source,
    [locale],
  );
  const domainMessage = useCallback(
    (source: string, code?: string | null) =>
      DOMAIN_MESSAGES[source]?.[locale]
      ?? (code ? DOMAIN_MESSAGES[code] : undefined)?.[locale]
      ?? (locale === "en" ? ENGLISH[source] ?? source : source),
    [locale],
  );
  return {
    locale,
    t,
    domainMessage,
    publicationStatus: (status: string) => PUBLICATION_STATUSES[status]?.[locale] ?? status,
    executionStatus: (status: string) => EXECUTION_STATUSES[status]?.[locale] ?? status,
    dateLocale: locale === "en" ? "en-US" : "zh-CN",
  };
}
